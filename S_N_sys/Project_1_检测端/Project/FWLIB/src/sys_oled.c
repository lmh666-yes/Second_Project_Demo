/* ================================================================
 *  sys_oled.c —— 【外接】OLED 显示模块（SSD1306, I2C）  实现文件
 * ================================================================
 *  实现要点 :
 *    ① "显存缓冲 + 整帧刷新":所有 ShowXxx/SetPixel 改 1024 字节内存,
 *       SYS_OLED_Refresh 才把整帧流式发到屏(无闪烁、可批量改后一次刷);
 *    ② 初始化 = 命令表循环发送(加/减命令只改表,见 oled_init_seq);
 *    ③ 内置 8x8 ASCII 点阵已转成"列排"(每列 1 字节,bit0 = 顶端),
 *       与页格式显存一一对应——显示字符是"直拷",零运算;
 *    ④ 所有通信经 sys_i2c(自带超时/错误码,总线异常不会死等卡死)
 *
 *  显存结构(SSD1306 页格式):
 *    oled_buf[p * 128 + x] 是第 p 页(8 行一群)、第 x 列那 8 个像素;
 *    bit0 = 页内第 0 行(最上),bit7 = 第 7 行;
 *    8 页 × 128 列 = 1024 字节 = 整屏。
 * ================================================================ */


/* ================================================================
 *                    内部状态与数据表
 * ================================================================ */
static SysI2cId_t s_bus  = SYS_I2C_1;           /* 记住初始化时的总线 */
