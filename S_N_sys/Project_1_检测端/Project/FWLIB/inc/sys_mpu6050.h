#ifndef __FWLIB_SYS_MPU6050_H
#define __FWLIB_SYS_MPU6050_H

#include "stm32f4xx.h"
#include "sys_i2c.h"

/* ================================================================
 *  sys_mpu6050.h —— 【板载】六轴传感器 MPU6050  头文件
 * ================================================================
 *  设计定位 : 板载 MPU6050(三轴加速度 + 三轴陀螺 + 温度)的"薄封装"
 *             —— 初始化自检(WHO_AM_I)+ 一次突发读 14 字节 + 物理量换算
 *             —— 姿态角(pitch/roll)用加速度推算,给"静态倾角"用
 *  标准库关键词 : 无——器件寄存器读写全部走 sys_i2c(见其文件头调用示例)
 *
 *  本板接线 : 板载挂在 I2C1(PB8 = SCL / PB9 = SDA,与 24C02 同总线),
 *             器件地址 0x68(AD0 接地)
 *
 *  使用方式 :
 *      if (SYS_MPU6050_Init(SYS_I2C_1) == 0) {        // 0 = WHO_AM_I 检查通过
 *          SYS_MPU6050_Data_t d;
 *          SYS_MPU6050_Read(SYS_I2C_1, &d);           // d.ax..gz = 物理量
 *          SYS_OLED_ShowFloat(3, 0, d.ax, 2);         // 配合 OLED 显示
 *      }
 *  重要说明 :
 *      ① 加速度单位 g、陀螺单位 °/s、温度 ℃(换算按区块 1 的量程宏);
 *      ② 姿态角用加速度反算,静止/慢速准确,快速晃动会抖——
 *         要平稳角度需"陀螺积分 + 加速度校正"(互补滤波/卡尔曼),
 *         本模块只给原始量 + 静态倾角,滤波留给上层(见 sys_filter);
 *      ③ 静止时读数仍有零偏,做精确积分前建议先"静止采几百次求均值"
 *         当零偏扣除(扩展方向,注释里有提示位置)
 * ================================================================ */


/* ================================================================
 *                    区块 1：定义与宏定义区（换板子只改这里）
 * ================================================================ */
/* 器件 7 位地址(AD0 接地 = 0x68;接高 = 0x69 时改这里) */
#define SYS_MPU6050_ADDR        SYS_I2C_ADDR_MPU6050    /* 0x68 */

/* 陀螺量程: 0=±250 1=±500 2=±1000 3=±2000 (°/s)——越大越不怕转飞,
 * 但分辨率越粗(±250 时约 131 LSB/(°/s),±2000 时约 16.4) */
#define SYS_MPU6050_GYRO_FS     0

/* 加计量程: 0=±2g 1=±4g 2=±8g 3=±16g——静态倾角用 ±2g 分辨率最高 */
#define SYS_MPU6050_ACCEL_FS    0

/* 采样分频: 采样率 = 1kHz ÷ (1 + 该值)。7 → 125Hz(通用值) */
#define SYS_MPU6050_SMPLRT_DIV  7


/* ================================================================
 *                    区块 2：基础功能
 * ================================================================ */
/* 原始 16 位读数(温度也是 16 位,未换算)——排查/调试用 */
typedef struct {
    int16_t ax, ay, az;     /* 加速度原始值 */
    int16_t temp;           /* 温度原始值: ℃ = temp/340 + 36.53 */
    int16_t gx, gy, gz;     /* 陀螺原始值 */
} SYS_MPU6050_Raw_t;

/* 初始化: 自检 + 唤醒 + 按区块 1 宏配置量程与采样率
 * 返回 : 0 = 成功;1 = 无应答或 WHO_AM_I 不是 0x68(器件没接好/不是 6050)
 * 标准库调用链 : 无直调标准库——经 sys_i2c 读 0x75 自检,
 *                再写 0x6B/0x19/0x1A/0x1B/0x1C 共 5 个配置寄存器
 * 示例 : if (SYS_MPU6050_Init(SYS_I2C_1) != 0) { printf("MPU6050 不在线\r\n"); } */
uint8_t SYS_MPU6050_Init(SysI2cId_t bus);

/* 读一次原始数据(7 个 int16:加速度 xyz + 温度 + 陀螺 xyz)
 * 返回 : SYS_I2C_OK(0) = 成功;负数 = I2C 错误码(见 sys_i2c.h)
 * 说明 : 一次突发读 14 字节——保证 14 个字节来自"同一时刻"(寄存器自增)
 * 示例 : SYS_MPU6050_Raw_t r; SYS_MPU6050_ReadRaw(SYS_I2C_1, &r); */
int SYS_MPU6050_ReadRaw(SysI2cId_t bus, SYS_MPU6050_Raw_t *out);


/* ================================================================
 *                    区块 3：扩展功能
 * ================================================================ */
/* 物理量数据(换算后) */
typedef struct {
    float ax, ay, az;       /* 加速度,单位 g(1g ≈ 9.8m/s²) */
    float gx, gy, gz;       /* 角速度,单位 °/s */
    float temp_c;           /* 温度,单位 ℃ */
} SYS_MPU6050_Data_t;

/* 读一次并换算成物理量(按区块 1 的量程宏自动选灵敏度)
 * 返回 : 0 = 成功;负数 = I2C 错误码
 * 示例 : SYS_MPU6050_Data_t d;
 *        if (SYS_MPU6050_Read(SYS_I2C_1, &d) == 0) {
 *            printf("ax=%.2fg gz=%.1f deg/s temp=%.1f C\r\n", d.ax, d.gz, d.temp_c);
 *        } */
int SYS_MPU6050_Read(SysI2cId_t bus, SYS_MPU6050_Data_t *out);

/* 静态倾角(用加速度反算):pitch = 俯仰角(绕 Y 轴),roll = 横滚角(绕 X 轴)
 * 说明 : 单位"度";静止/慢速时准确,快速晃动时受运动加速度干扰——
 *        需要动态平稳角度请做互补滤波: 角度 = 0.98×(角度+陀螺积分×dt)
 *        + 0.02×本次加速度倾角(经典公式,留给上层实现)
 * 参数 : 输出指针可为 NULL(只要其中一个)
 * 示例 : float pitch, roll;
 *        SYS_MPU6050_ReadPitchRoll(SYS_I2C_1, &pitch, &roll); */
int SYS_MPU6050_ReadPitchRoll(SysI2cId_t bus, float *pitch_deg, float *roll_deg);

/* 读 WHO_AM_I(0x75,正常值 0x68)——排查"接的是什么器件"用
 * 返回 : 0~255;读失败返回 -1
 * 示例 : int who = SYS_MPU6050_GetID(SYS_I2C_1);   // 正常 = 104(0x68) */
int SYS_MPU6050_GetID(SysI2cId_t bus);

#endif /* __FWLIB_SYS_MPU6050_H */
