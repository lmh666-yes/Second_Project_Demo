#ifndef __FWLIB_SYS_DHT11_H
#define __FWLIB_SYS_DHT11_H

#include "stm32f4xx.h"

/* ================================================================
 *  sys_dht11.h —— 【板载】温湿度传感器 DHT11  头文件
 * ================================================================
 *  设计定位 : 单总线温湿度器件的"薄封装"—— 起始信号、80us 应答、
 *             40 位数据、校验和全部在库内完成,调用一次拿结果
 *  标准库关键词 : 无——纯 GPIO 位翻转时序;微秒测量用内核 DWT 周期
 *                 计数器(见 gpio_core 的"精准延时"小节同源技术)
 *
 *  本板接线 : 板载 DHT11 数据脚 = PG9(区块 1 宏;换板改宏或用参数)
 *             板上已有上拉电阻;直插器件时注意面向(网面朝自己,
 *             左起 1=VCC 2=DATA 3=NC 4=GND)
 *
 *  使用方式 :
 *      SYS_DHT11_Init(SYS_DHT11_PORT, SYS_DHT11_PIN);   // ① 初始化(1 次)
 *      float t, h;
 *      if (SYS_DHT11_Read(&t, &h) == 0) {               // ② 读一次
 *          SYS_OLED_ShowFloat(4, 0, t, 1);              // 温度
 *          SYS_OLED_ShowFloat(5, 0, h, 1);              // 湿度
 *      }
 *  重要说明 :
 *      ① 读一次约 5ms,期间默认关中断(SYS_DHT11_LOCK_IRQ=1)——上 FreeRTOS
 *         时会推迟调度几毫秒;建议放在专用任务里"每 2s 读一次"
 *         (DHT11 本身采样率只有 1Hz,读快了反而拿到旧值);
 *      ② 首次上电需稳定约 1s 再读(器件内部初始化);
 *      ③ 返回值: 0 = 成功; -1 = 无响应(断线/引脚错/没上拉);
 *         -2 = 校验失败(线太长/干扰大)——连续失败请缩短杜邦线;
 *      ④ 精度: 湿度 ±5%RH、温度 ±2℃,小数量级数的"小数位"实际为 0
 *         (DHT11 特性,不是读错了)
 * ================================================================ */


/* ================================================================
 *                    区块 1：定义与宏定义区（换板子只改这里）
 * ================================================================ */
/* 板载 DHT11 数据脚(PG9)——初始化时按参数传入,宏只是本板默认值 */
#define SYS_DHT11_PORT      GPIOG
#define SYS_DHT11_PIN       GPIO_Pin_9

/* 1 = 读时序期间关中断(默认,最稳);0 = 不关(实时性优先,
 * 但中断抖动可能导致校验失败——长任务/RTOS 抖动大时别关这个) */
#define SYS_DHT11_LOCK_IRQ  1


/* ================================================================
 *                    区块 2：基础功能
 * ================================================================ */
/* 初始化: 记录引脚并把总线置为空闲态(输入+上拉)
 * 示例 : SYS_DHT11_Init(SYS_DHT11_PORT, SYS_DHT11_PIN); */
void SYS_DHT11_Init(GPIO_TypeDef *port, uint16_t pin);

/* 读温湿度(阻塞约 5ms)
 * 参数 : temp_c / humi_rh —— 输出:温度℃ / 湿度%RH(任一可为 NULL 跳过)
 * 返回 : 0 = 成功; -1 = 无响应; -2 = 校验失败
 * 标准库调用链 : 无直调标准库——纯 GPIO 方向/电平翻转 + DWT 周期计数:
 *        拉低 18ms → 释放 → 等应答(80us 低 + 80us 高) →
 *        40 位循环(每位的"高电平时长"过 50us 判为 1)
 * 示例 : float t, h;
 *        if (SYS_DHT11_Read(&t, &h) == 0) { ... } */
int SYS_DHT11_Read(float *temp_c, float *humi_rh);

#endif /* __FWLIB_SYS_DHT11_H */
