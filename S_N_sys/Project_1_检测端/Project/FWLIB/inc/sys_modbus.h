#ifndef __FWLIB_SYS_MODBUS_H
#define __FWLIB_SYS_MODBUS_H

#include "stm32f4xx.h"
#include "sys_usart.h"

/* ================================================================
 *  sys_modbus.h —— 【系统】Modbus-RTU 从机(下位机)协议模块  头文件
 * ================================================================
 *  设计定位 : Modbus-RTU 从机的"薄封装"—— 收帧、CRC 校验、功能码分发、
 *             应答组装全部在库内;应用只做两件事:
 *               ① 提供"寄存器数组"当数据窗口(采集结果写进去);
 *               ② 主循环里反复调用 SYS_MODBUS_Poll()
 *  标准库关键词 : 无——帧收发走 sys_usart;帧间隔(3.5 字符)用 DWT 计时;
 *                 校验 = CRC16(Modbus 多项式 0xA001)
 *  角色说明 : 典型拓扑 = 你的板子当"从机",Qt / 组态屏 / PLC 当"主机"
 *             定时轮询。支持的功能码:
 *               0x03 读保持寄存器(可读可写区)   0x04 读输入寄存器(只读区)
 *               0x06 写单个保持寄存器           0x10 写多个保持寄存器
 *
 *  使用方式 :
 *      static uint16_t hold[16];      // 主机可读可写 → 40001 起
 *      static uint16_t input[8];      // 主机只读     → 30001 起
 *      SYS_USART_InitRxIT(SYS_USART_2, 9600);     // ① 串口开"中断接收"
 *      SYS_MODBUS_Init(SYS_USART_2, 1, 9600, hold, 16, input, 8);  // ② 从机地址 = 1
 *      while (1) { SYS_MODBUS_Poll(); 其它任务... } // ③ 主循环常刷(非阻塞)
 *  重要说明 :
 *      ① 寄存器地址 = 数组下标(从 0 算):主机侧 40001 ↔ hold[0]、
 *         30001 ↔ input[0](Qt 上位机侧记得做这个偏移换算);
 *      ② RS485 收发器场景:把 SYS_RS485_Send 包装成"发送钩子"注册给本模块
 *         (SYS_MODBUS_SetTxHook),应答就会自动带方向切换;
 *      ③ 前提 = 该串口已 SYS_USART_InitRxIT(字节靠中断进环形缓冲);
 *         不要与 DMA 接收(RecvDMA)模式混用同一路串口;
 *      ④ 多任务:寄存器数组的"读改写"集中在本流程/任务里最省心;
 *         其它任务只做"单个 uint16 赋值"(16 位写天然原子)即可安全共享;
 *      ⑤ 不支持广播(地址 0)与 0x01/0x05/0x0F 线圈类功能码——用到再扩;
 *      ⑥ 帧间隔判定按"3.5 字符时间"自动计算(波特率 > 19200 时按规范用
 *         固定 1750us);波特率必须与主机一致
 * ================================================================ */


/* ================================================================
 *                    区块 1：定义与宏定义区（换板子只改这里）
 * ================================================================ */
/* 帧缓冲大小(字节):理论上最长帧 = 1+1+1+250+2 = 255,留 1 字节余量 */
#define SYS_MODBUS_BUF_SIZE 256


/* ================================================================
 *                    区块 2：基础功能
 * ================================================================ */
/* 计算 Modbus-RTU 的 CRC16(多项式 0xA001,初值 0xFFFF)
 * 返回 : 16 位校验值;发送顺序 = 低字节在前、高字节在后
 * 用途 : ① 模块内部用它校验收帧/组装应答;② 你写"主机侧"程序
 *        (STM32 主动去问别的从机)时组装请求帧也要用它
 * 巧用 : 对"含 CRC 的完整帧"再算一遍,结果为 0 即校验通过
 * 示例 : uint16_t c = SYS_MODBUS_Crc16(frame, len); */
uint16_t SYS_MODBUS_Crc16(const uint8_t *buf, uint16_t len);

/* 初始化: 绑定串口 / 从机地址 / 波特率 / 两个寄存器数组
 * 参数 : uart —— 串口编号(须已 InitRxIT);addr —— 从机地址 1~247;
 *        baud —— 波特率(只用于算帧间隔,须与实际一致);
 *        hold/hold_n —— 保持寄存器数组(0x03/0x06/0x10 的目标,可传 0/0 不用);
 *        input/input_n —— 输入寄存器数组(0x04 的目标,可传 0/0 不用)
 * 示例 : SYS_MODBUS_Init(SYS_USART_2, 1, 9600, hold, 16, input, 8);
 *        // 从机一号:主机可读写 40001~40016、只读 30001~30008 */
void SYS_MODBUS_Init(SysUsartId_t uart, uint8_t addr, uint32_t baud,
                     uint16_t *hold, uint16_t hold_n,
                     uint16_t *input, uint16_t input_n);

/* 协议轮询(非阻塞):搬运串口字节 + 帧间隔到点就处理并应答
 * 返回 : 本次处理的帧数(0 = 无事发生;1 = 处理了一帧)
 * 调用 : 主循环里常刷(或放独立任务循环)——单次开销极小
 * 示例 : while (1) { SYS_MODBUS_Poll(); 其它任务... } */
uint8_t SYS_MODBUS_Poll(void);


/* ================================================================
 *                    区块 3：扩展功能
 * ================================================================ */
/* 应答发送函数原型(接 RS485 等自定义发送路径用) */
typedef void (*SYS_MODBUS_TxFn_t)(const uint8_t *buf, uint16_t len);

/* 注册"应答发送钩子"——RS485 场景接上方向控制
 * 说明 : 注册后所有应答都改走该函数;不注册则直接 SYS_USART_SendBuf
 * 示例 : static void my_tx(const uint8_t *b, uint16_t l) {
 *            SYS_RS485_Send(SYS_USART_2, b, l);    // 自动切方向
 *        }
 *        SYS_MODBUS_SetTxHook(my_tx); */
void SYS_MODBUS_SetTxHook(SYS_MODBUS_TxFn_t fn);

/* 读统计:成功处理帧数 / 出错帧数(CRC 错、参数非法等)——排查用
 * 参数 : ok / err 输出指针可为 NULL(不要哪个传 0)
 * 示例 : uint16_t ok, err; SYS_MODBUS_Counters(&ok, &err); */
void SYS_MODBUS_Counters(uint16_t *ok, uint16_t *err);

#endif /* __FWLIB_SYS_MODBUS_H */
