#ifndef __FWLIB_ULN2003_H
#define __FWLIB_ULN2003_H

#include "stm32f4xx.h"

/* ================================================================
 *  uln2003.h —— 【板载】步进电机驱动（ULN2003D + 5 线减速步进）  头文件
 * ================================================================
 *  设计定位 : 把"四相步进电机"变成 4 个函数调用——正转/反转/走 N 步/停
 *  依赖     : 只用 gpio_core（普通 GPIO 推挽输出），**不依赖任何定时器**
 *  标准库关键词 : GPIO_Init / GPIO_SetBits / GPIO_ResetBits（经 gpio_core）
 *
 *  【这块板上的电机模块长什么样（原理图逐脚核对）】
 *      U10 = ULN2003D（7 路达林顿驱动阵列，不是 H 桥！）
 *      U10 的 IN1~IN4 ← 网络 `MOTO_IN1`~`MOTO_IN4`
 *      U10 的 OUT1~OUT4 → 网络 `OUT1`~`OUT4`
 *      U10 的 COM(9 脚) ← 5V（步进电机公共端要接 5V）
 *
 *      对外两个排针（都在板上丝印有标）:
 *        · J11（5 脚，丝印 `5V / 01 / 02 / 03 / 04`）—— **插电机**
 *              5V 接 28BYJ-48 的红线，01~04 接其余四根相线
 *        · CN2（4 脚，丝印 `T1 / T2 / T3 / T4`）—— **控制输入**
 *              即 `MOTO_IN1`~`MOTO_IN4`，对应 U10 的 IN1~IN4
 *
 *  ⚠⚠ **重要：CN2 没有硬连到 MCU 的引脚**！
 *      原理图上 `MOTO_IN1~4` 只走到 CN2 排针就没了，也就是说：
 *      **你必须自己用杜邦线，从扩展排针（P9）挑 4 个空闲 IO 接到 CN2 的 T1~T4**。
 *      所以下面 4 个引脚宏**是给\"你打算用哪 4 个脚\"填的**，
 *      默认给了一组本板完全空闲的脚（PC1~PC4），你按实际接线改即可。
 *      本板未占用的脚有：PA1 / PA7 / PB5 / PB12 / PB13 /
 *                        PC1~PC5 / PC12 / PD3 / PG11 / PG13 / PG14
 *
 *  【什么是"四相八拍"（面试点）】
 *      减速步进电机内部有 4 组线圈（A/B/C/D）。给线圈按固定顺序通电，
 *      转子就会一格一格转过去。两种常用驱动方式：
 *        · 四相四拍（A-B-C-D）      —— 一步转得多、力矩小、有轻微抖动
 *        · 四相八拍（A-AB-B-BC-C-CD-D-DA）—— 步距减半、更平滑，本库默认
 *      两相同时通电（AB）时力矩最大，这就是八拍比四拍平滑的原因。
 *
 *  使用方式 :
 *      ULN2003_Init();
 *      ULN2003_Step(2038, 1);      // 28BYJ-48 内部减速比 1:64，正转一圈约 2038 步
 *      ULN2003_Stop();             // 松手（线圈断电，省电、不发热）
 *
 *  移植指引 : 换引脚改"区块 1"的 4 个宏；换驱动方式改 ULN2003_MODE；
 *             换电机（不同减速比/步距角）用 ULN2003_StepsPerRev 自己算。
 * ================================================================ */


/* ================================================================
 *                    区块 1：定义与宏定义区（换板子只改这里）
 * ================================================================ */
/* 0 = 不编译本模块 */
#ifndef ULN2003_ENABLE
#define ULN2003_ENABLE      1
#endif

/* -------------------- 控制引脚（★按你实际接到 CN2 的线改） -------------------- */
/* 顺序必须与 CN2 的 T1/T2/T3/T4 一一对应 */
#define MOTOR_IN1_PORT      GPIOC
#define MOTOR_IN1_PIN       GPIO_Pin_1
#define MOTOR_IN2_PORT      GPIOC
#define MOTOR_IN2_PIN       GPIO_Pin_2
#define MOTOR_IN3_PORT      GPIOC
#define MOTOR_IN3_PIN       GPIO_Pin_3
#define MOTOR_IN4_PORT      GPIOC
#define MOTOR_IN4_PIN       GPIO_Pin_4

/* -------------------- 驱动方式 -------------------- */
/* 1 = 四相八拍（A-AB-B-BC-C-CD-D-DA）—— 平滑，推荐
 * 0 = 四相四拍（A-B-C-D）              —— 简单，力矩略小 */
#define ULN2003_MODE_8BEAT  1

/* -------------------- 每转步数（28BYJ-48 减速步进） -------------------- */
/* 28BYJ-48：步距角 5.625°/64（内置 1:64 减速）
 *   八拍：360 / (5.625/64) / 2 = 2048 步/圈（常见取值 2038，差值是齿轮间隙）
 * 换别的电机 → 按手册算：步/圈 = 360 / 步距角 * 减速比 */
#define ULN2003_STEPS_PER_REV   2038U

/* -------------------- 每步间隔（微秒） -------------------- */
/* 一步走完后等多久再走下一位。太小 → 电机来不及响应（丢步、嗡嗡响）；
 * 太大 → 转得慢。常用 1000~3000us（约 300~1000 步/秒）
 * ⚠ 这个值是"阻塞式"的：ULN2003_Step 会在这里面空等，
 *   要一边转一边干别的事请用 ULN2003_Tick（自己在定时器里调） */
#define ULN2003_STEP_DELAY_US   1500U

/* -------------------- 通电/断电的极性 -------------------- */
/* ULN2003 是"输入高 → 对应输出拉到 GND"，也就是**灌电流**驱动。
 * 所以"这一相通电"= 对应 IN 脚给高电平（1）。若你的接线是反的，改成 0 */
#define ULN2003_ACTIVE_HIGH     1


/* ================================================================
 *                    区块 2：基础功能
 * ================================================================ */
/* 初始化 4 个控制脚（推挽输出 GPIO_OType_PP）并把电机停住（线圈全断电）
 * 标准库 : RCC_AHB1PeriphClockCmd + GPIO_Init（经 gpio_core 的
 *          GPIO_ClockEnable / GPIO_OutInit）
 * 示例 : ULN2003_Init(); */
void ULN2003_Init(void);

/* 走指定步数（**阻塞**：整段走完才返回）
 * 参数 : steps —— 步数（1 ~ 约 4 亿）；dir —— 1 = 正转(CCW)，0 = 反转(CW)
 * 说明 : 每步之间按 ULN2003_STEP_DELAY_US 延时；
 *        走完**不会自动断电**（保持最后一相通电 = 保持力矩），
 *        想省电请在最后调 ULN2003_Stop()
 * 示例 : ULN2003_Step(ULN2003_STEPS_PER_REV, 1);   // 正转一圈 */
void ULN2003_Step(uint32_t steps, uint8_t dir);

/* 断电停车（4 相通电全断 → 转子失去保持力矩，可用手轻轻转动）
 * 示例 : ULN2003_Stop(); */
void ULN2003_Stop(void);

/* 给 4 相全部通电（"锁死"模式：力矩最大，但发热也最大，别长期用）
 * 示例 : ULN2003_Hold(); */
void ULN2003_Hold(void);


/* ================================================================
 *                    区块 3：扩展功能
 * ================================================================ */
/* 只走**一步**（非阻塞的关键一环）
 * 参数 : dir —— 1 = 正转，0 = 反转
 * 说明 : 调用一次就让相位前进/后退一格并立刻返回，**不带延时**。
 *        想"一边转一边干别的"——把它放进 sys_tick / sys_tim 的
 *        周期性回调里，每 ULN2003_STEP_DELAY_US 调一次即可。
 * 示例 : ULN2003_OneStep(1);   // 相位走一格 */
void ULN2003_OneStep(uint8_t dir);

/* 当前相位序号（0 ~ 7，八拍模式；四拍模式只用到 0~3）
 * 示例 : printf("phase = %d\r\n", ULN2003_GetPhase()); */
uint8_t ULN2003_GetPhase(void);

/* 复位相位到 0（不影响电机位置，只是让软件计数归零）
 * 说明 : 换向或重新起转前调一次，可避免"第一步方向抖一下" */
void ULN2003_ResetPhase(void);

/* 直接设定转速（每步延时，单位微秒；内部会存进一个变量）
 * 参数 : us —— 100 ~ 20000；超出自动截断
 * 说明 : 改的是运行时值，ULN2003_Step 里用它替换默认宏；
 *        想"加速启动"可以每走一小段就调小一点。
 * 示例 : ULN2003_SetStepDelay(800);   // 加快到 800us/步 */
void ULN2003_SetStepDelay(uint32_t us);
uint32_t ULN2003_GetStepDelay(void);

#endif /* __FWLIB_ULN2003_H */
