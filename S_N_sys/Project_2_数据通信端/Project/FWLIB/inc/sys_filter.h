#ifndef __FWLIB_SYS_FILTER_H
#define __FWLIB_SYS_FILTER_H

#include "stm32f4xx.h"

/* ================================================================
 *  sys_filter.h —— 【算法】数字滤波工具集  头文件
 * ================================================================
 *  设计定位 : 传感器数据处理常用的小工具（无状态函数 + 一个低通对象）
 *             光电信号、ADC 采样、编码器测速都能用上
 *  依赖     : 无（纯算法，不依赖任何硬件）
 *
 *  【四种滤波怎么选（面试常问）】
 *    · 限幅滤波  FILTER_Limit      —— 专门治"偶发大跳变"（尖刺/野值）
 *    · 中值滤波  FILTER_Median     —— 专门治"孤立野值"，且不损失阶跃响应
 *    · 滑动平均  FILTER_MovingAvg  —— 平滑随机噪声，但会滞后（阶跃变缓）
 *    · 一阶低通  FILTER_Lpf*       —— 计算量最小、参数直观，闭环控制首选
 *    · 去极值平均 FILTER_TrimmedMean —— 去掉最大最小再平均（比赛常用）
 *
 *  【工程建议】
 *    ① 传感器原始值先"限幅"（防野值），再"低通/平均"（降噪声），最后进算法；
 *    ② 低通系数 α 越小越平滑但越滞后——闭环控制里滞后会吃掉相位裕度，
 *       所以控制环上的 α 别调得过小（一般 0.1~0.3）；
 *    ③ 滑动平均/中值都需要一个 RAM 缓冲，缓冲长度建议 4~16（2 的幂最快）。
 * ================================================================ */


/* ================================================================
 *                    区块 1：定义与宏定义区
 * ================================================================ */
/* 采样缓冲区最大长度（你要用滑动平均/中值/去极值平均时，数组开这么大即可） */
#define FILTER_BUF_MAX      32


/* ================================================================
 *                    区块 2：无状态滤波（一次调用出结果）
 * ================================================================ */
/* 限幅滤波：本次值与上次值相差超过 max_step 就"不信任本次"，保持上次值
 * 参数 : prev —— 上次的输出；now —— 本次采样；max_step —— 允许的最大变化量
 * 返回 : 滤波后的值
 * 适用 : 有明显尖刺的传感器（超声波、红外测距、开关电源干扰）
 * 示例 : adc = FILTER_Limit(adc, new_raw, 50);   // 一次最多变 50 */
uint16_t FILTER_Limit(uint16_t prev, uint16_t now, uint16_t max_step);

/* 中值滤波：对 buf[0..n-1] 排序后取中间值（会**修改** buf 内容）
 * 参数 : buf/n —— 数据缓冲与个数（n 建议取奇数；n<=0 返回 0）
 * 返回 : 中位数
 * 适用 : 剔除孤立野值，且不像平均那样拖慢阶跃
 * 示例 : uint16_t s[5];  采集 5 次装进 s → FILTER_Median(s, 5); */
uint16_t FILTER_Median(uint16_t *buf, uint16_t n);

/* 滑动平均（算术平均）：求 buf[0..n-1] 的平均值（不修改 buf）
 * 返回 : 平均值（按四舍五入取整）
 * 适用 : 随机噪声平滑；n 越大越平滑、越滞后 */
uint16_t FILTER_MovingAvg(const uint16_t *buf, uint16_t n);

/* 去极值平均：去掉最大的 trim 个和最小的 trim 个，再对剩下的求平均
 * 参数 : buf/n —— 数据；trim —— 两端各去掉几个（n 必须 > 2*trim）
 * 返回 : 平均值；参数非法时退回普通平均
 * 适用 : 采样环境有随机尖刺又不想被中值"吃掉"细节（电子设计竞赛常用）
 * 示例 : FILTER_TrimmedMean(s, 10, 2);   // 10 个数去掉最大 2 个最小 2 个 */
uint16_t FILTER_TrimmedMean(uint16_t *buf, uint16_t n, uint16_t trim);

/* 极值统计辅助：求 buf 的最大/最小值（不修改 buf）
 * 示例 : uint16_t mx, mn; FILTER_MinMax(s, 10, &mn, &mx); */
void FILTER_MinMax(const uint16_t *buf, uint16_t n, uint16_t *min_out, uint16_t *max_out);


/* ================================================================
 *                    区块 3：一阶低通（IIR，最常用的"有状态"滤波）
 * ================================================================
 * 公式： y[n] = α·x[n] + (1-α)·y[n-1]
 *   · α 越大越"信任新数据"（响应快、平滑弱）
 *   · α 越小越"信任历史"（平滑强、滞后大）
 *   α 与截止频率的关系：α ≈ 2π·fc/fs（fc << fs 时成立）
 *   本库的 FILTER_LpfInit 直接按"截止频率 + 采样率"帮你算 α。
 * ================================================================ */
typedef struct {
    float  alpha;      /* 平滑系数 0~1（越大越灵敏） */
    float  y;          /* 上次输出 */
    uint8_t started;   /* 首次调用标志（第一拍直接取输入，避免从 0 爬升） */
} FilterLpf_t;

/* 初始化低通：按截止频率与采样率自动算 α
 * 参数 : f     —— 滤波器对象
 *        fc_hz —— 截止频率 Hz（想滤掉 50Hz 工频，fc 取 10~20Hz）
 *        fs_hz —— 采样率 Hz（即你多久调用一次 Update）
 * 示例 : FilterLpf_t lpf;
 *        FILTER_LpfInit(&lpf, 20.0f, 100.0f);   // 20Hz 截止、100Hz 采样 */
void  FILTER_LpfInit(FilterLpf_t *f, float fc_hz, float fs_hz);

/* 直接设置 α（不想算截止频率、只想"拧一个 0.0~1.0 的旋钮"时用）
 * 经验 : 0.1 很平滑、0.3 折中、0.5 以上基本就没滤多少了 */
void  FILTER_LpfSetAlpha(FilterLpf_t *f, float alpha);

/* 喂一个新采样，返回滤波结果 */
float FILTER_LpfUpdate(FilterLpf_t *f, float x);

/* 复位（清历史，下次调用重新起步） */
void  FILTER_LpfReset(FilterLpf_t *f);

#endif /* __FWLIB_SYS_FILTER_H */
