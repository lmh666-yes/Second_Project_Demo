static QString clean(const QHash<QString, QString> &answers, const QString &id)
{
    return answers.value(id).trimmed();
}

QString renderMarkdown(const QString &name, const QHash<QString, QString> &answers)
{
    const QString title = name.trimmed().isEmpty() ? QStringLiteral("未命名项目") : name.trimmed();
    QStringList out;
    out << QStringLiteral("# %1").arg(title);
    out << QString();
    out << QStringLiteral("> 由项目起手助手生成的设计文档骨架。逐节补完后，可当作项目的设计思路报告使用。");
    out << QString();

    QVector<PageSpec> specs = defaultSpecs();
    QStringList missing;

    for (const PageSpec &page : specs) {
        out << QStringLiteral("## %1").arg(page.title);
        out << QString();
        for (const FieldSpec &f : page.fields) {
            out << QStringLiteral("### %1").arg(f.label);
            out << QString();
            const QString v = clean(answers, f.id);
            if (v.isEmpty()) {
                out << QStringLiteral("（未填写）");
                missing << QStringLiteral("%1 / %2").arg(page.title, f.label);
            } else if (f.multi) {
                for (const QString &line : v.split('\n')) {
                    out << QStringLiteral("- %1").arg(line.trimmed().isEmpty() ? QStringLiteral("（空行）") : line.trimmed());
                }
            } else {
                out << v;
            }
            out << QString();
        }
    }

    out << QStringLiteral("## 附：待确认项");
    out << QString();
    if (missing.isEmpty()) {
        out << QStringLiteral("无。全部字段已填写。");
    } else {
        for (const QString &m : missing) {
            out << QStringLiteral("- %1").arg(m);
        }
    }
    out << QString();

    return out.join('\n');
}
