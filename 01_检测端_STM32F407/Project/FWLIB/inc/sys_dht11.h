#ifndef __FWLIB_SYS_DHT11_H
#define __FWLIB_SYS_DHT11_H

#include "stm32f4xx.h"

/* sys_dht11.h — 板载 DHT11 温湿度传感器头文件
 * 接线 : 数据脚 PG9；板上已有上拉；直插器件 1=VCC 2=DATA 3=NC 4=GND
 * 时序 : 一次读取约 5ms，期间默认关中断；上电需稳定约 1s；采样率 1Hz
 * 说明 : 返回值定义与异常排查见 SYS_DHT11_Read / SYS_DHT11_GetRaw */


/* ================================================================
 *                    区块 1：定义与宏定义区
 * ================================================================ */
/* 板载 DHT11 数据脚(PG9)，初始化时按参数传入，宏仅为本板默认值 */
#define SYS_DHT11_PORT      GPIOG
#define SYS_DHT11_PIN       GPIO_Pin_9

/* 1 = 读时序期间关中断(默认)；0 = 不关，中断抖动可能导致校验失败 */
#define SYS_DHT11_LOCK_IRQ  1


/* ================================================================
 *                    区块 2：基础功能
 * ================================================================ */
/* 初始化: 记录引脚并把总线置为空闲态(输入+上拉) */
void SYS_DHT11_Init(GPIO_TypeDef *port, uint16_t pin);

/* 读温湿度(阻塞约 5ms)
 * 参数 : temp_c / humi_rh — 输出: 温度℃ / 湿度%RH(任一可为 NULL 跳过)
 * 返回 : 0 = 成功; -1 = 无响应(断线/引脚错/没上拉); -2 = 校验失败
 * 精度 : 湿度 ±5%RH、温度 ±2℃，小数位恒为 0
 * 时序 : 拉低 18ms → 释放 → 等应答(80us 低 + 80us 高) → 40 位(高电平
 *        时长 > 50us 判为 1)；实现为纯 GPIO 翻转 + DWT 周期计数 */
int SYS_DHT11_Read(float *temp_c, float *humi_rh);

/* 取回最近一次 SYS_DHT11_Read() 采到的 5 个原始字节(排障用)
 * 参数 : raw — 至少 5 字节的数组，按 [0]湿度整数 [1]湿度小数
 *        [2]温度整数 [3]温度小数 [4]校验和 填充
 * 返回 : 无；校验失败(-2)时据原始字节区分故障来源:
 *        全 0xFF → 器件没应答(接线/供电/没上拉)
 *        全 0x00 → 总线被拉死或方向设错
 *        个别位不同 → 时序抖动，缩短杜邦线或读期间不被打断 */
void SYS_DHT11_GetRaw(uint8_t raw[5]);

/* 带重试的读取
 * 参数 : temp_c / humi_rh — 输出; retries — 最多读几次(含第 1 次)
 * 返回 : 0 = 至少有一次读到并通过校验; -1 = 全部尝试都无响应;
 *        -2 = 有响应但每次都校验失败(多为硬件问题: 断线/没上拉/线太长)
 * 数值 : 每次尝试间隔 20ms，由器件 1Hz 采样率决定 */
int SYS_DHT11_ReadRetry(float *temp_c, float *humi_rh, uint8_t retries);

#endif /* __FWLIB_SYS_DHT11_H */
